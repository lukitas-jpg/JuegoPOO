package ar.edu.uade.rpg.modelo.tienda;

/**
 * Los seis simbolos de los rodillos, los mismos que las imagenes de la
 * maquina. Salen con la misma probabilidad: no hay ninguno "cargado".
 *
 * El DIAMANTE es el premio mayor. El LIMON es el chiste de la maquina, como en
 * las tragamonedas de verdad: es el unico trio que no paga nada.
 */
public enum Simbolo {
    MONEDA,
    CEREZA,
    TREBOL,
    RUBI,
    DIAMANTE,
    LIMON
}
